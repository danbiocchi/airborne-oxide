//! `oxide-sim params list | json | doc` (ADR-0004): the parameter table as a
//! listing, as QGroundControl parameter metadata, and as `docs/PARAMETERS.md`.

use std::fmt::Write as _;

use oxide_core::config::VehicleConfig;
use oxide_core::params::{self, PARAMS, ParamDef, ParamGroup, ParamId, ParamValue};
use oxide_sim::Airframe;

/// A value as text: an `i32` as is, an `f32` in its shortest round-trip form.
pub fn value_text(v: ParamValue) -> String {
    match v {
        ParamValue::F32(x) => format!("{x}"),
        ParamValue::I32(x) => format!("{x}"),
    }
}

fn type_text(d: &ParamDef) -> &'static str {
    match d.default {
        ParamValue::F32(_) => "Float",
        ParamValue::I32(_) => "Int32",
    }
}

fn change_text(d: &ParamDef) -> &'static str {
    if d.live { "live" } else { "disarmed" }
}

fn reference_config() -> Result<VehicleConfig<4>, oxide_sim::SimError> {
    Airframe::reference_quad()?.core_config::<4>()
}

/// `params list`: one line per parameter.
pub fn list() -> Result<String, Box<dyn std::error::Error>> {
    let cfg = reference_config()?;
    let mut out = String::new();
    let _ = writeln!(
        out,
        "{:<16} {:>12} {:>12} {:>12} {:>12} {:<6} {:<8} description",
        "name", "value", "default", "min", "max", "unit", "change"
    );
    for (i, d) in PARAMS.iter().enumerate() {
        let id = ParamId(u16::try_from(i)?);
        let value = params::get(&cfg, id).map_or("?".to_string(), value_text);
        let _ = writeln!(
            out,
            "{:<16} {:>12} {:>12} {:>12} {:>12} {:<6} {:<8} {}",
            d.name,
            value,
            value_text(d.default),
            value_text(d.min),
            value_text(d.max),
            d.unit,
            change_text(d),
            d.description
        );
    }
    Ok(out)
}

/// A JSON string literal: quotes, backslashes and control characters escaped.
pub fn json_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// `params json`: parameter metadata in the shape QGroundControl's component
/// metadata uses.
pub fn json() -> String {
    let mut out = String::from("{\n  \"version\": 1,\n  \"parameters\": [\n");
    for (i, d) in PARAMS.iter().enumerate() {
        let _ = write!(
            out,
            "    {{\"name\": {}, \"type\": {}, \"default\": {}, \"min\": {}, \"max\": {}, \"units\": {}, \"group\": {}, \"shortDesc\": {}, \"rebootRequired\": false}}",
            json_string(d.name),
            json_string(type_text(d)),
            value_text(d.default),
            value_text(d.min),
            value_text(d.max),
            json_string(d.unit),
            json_string(d.group.title()),
            json_string(d.description),
        );
        out.push_str(if i + 1 < PARAMS.len() { ",\n" } else { "\n" });
    }
    out.push_str("  ]\n}\n");
    out
}

fn md_cell(s: &str) -> String {
    s.replace('|', "\\|")
}

/// `params doc`: the text of `docs/PARAMETERS.md`.
pub fn doc() -> String {
    let mut out = String::new();
    out.push_str("# Parameters\n\n");
    out.push_str(
        "<!-- Generated by `oxide-sim params doc`. Do not edit by hand: change the table in `crates/oxide-core/src/params.rs` and regenerate. -->\n\n",
    );
    let _ = writeln!(
        out,
        "Every tunable value of the flight core is one of these {} parameters (ADR-0004). \
Set one for a simulated flight with `--param NAME=VALUE` (repeatable), with `--params FILE.toml` \
(a `[params]` table of `NAME = value`) or in the `[params]` table of an airframe file; \
they are applied in that order of increasing priority: airframe file, `--params` file, then the flags. \
A value outside its range, of the wrong type, or that would break a rule between two parameters is refused \
and the run does not start. Units are the core's own: radians, metres, seconds, volts. \
\"live\" parameters take effect in flight; \"disarmed\" ones are accepted only while disarmed.",
        PARAMS.len()
    );
    for group in ParamGroup::ALL {
        let _ = write!(out, "\n## {}\n\n", group.title());
        out.push_str("| Name | Type | Default | Min | Max | Unit | Change | Description |\n");
        out.push_str("|---|---|---|---|---|---|---|---|\n");
        for d in PARAMS.iter().filter(|d| d.group == group) {
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {} | {} | {} | {} | {} |",
                d.name,
                type_text(d),
                value_text(d.default),
                value_text(d.min),
                value_text(d.max),
                md_cell(d.unit),
                change_text(d),
                md_cell(d.description)
            );
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A minimal JSON value, enough to check what `json()` prints.
    #[derive(Debug, PartialEq)]
    enum J {
        Null,
        Bool(bool),
        Num(f64),
        Str(String),
        Arr(Vec<J>),
        Obj(Vec<(String, J)>),
    }

    struct P<'a> {
        s: &'a [u8],
        i: usize,
    }

    impl P<'_> {
        fn ws(&mut self) {
            while self.s.get(self.i).is_some_and(u8::is_ascii_whitespace) {
                self.i += 1;
            }
        }
        fn eat(&mut self, c: u8) -> Result<(), String> {
            self.ws();
            if self.s.get(self.i) == Some(&c) {
                self.i += 1;
                Ok(())
            } else {
                Err(format!("expected {} at {}", c as char, self.i))
            }
        }
        fn lit(&mut self, word: &str, v: J) -> Result<J, String> {
            if self.s[self.i..].starts_with(word.as_bytes()) {
                self.i += word.len();
                Ok(v)
            } else {
                Err(format!("bad literal at {}", self.i))
            }
        }
        fn string(&mut self) -> Result<String, String> {
            self.eat(b'"')?;
            let mut out: Vec<u8> = Vec::new();
            loop {
                let c = *self.s.get(self.i).ok_or("unterminated string")?;
                self.i += 1;
                match c {
                    b'"' => return String::from_utf8(out).map_err(|e| e.to_string()),
                    b'\\' => {
                        let e = *self.s.get(self.i).ok_or("bad escape")?;
                        self.i += 1;
                        match e {
                            b'"' | b'\\' | b'/' => out.push(e),
                            b'n' => out.push(b'\n'),
                            b'r' => out.push(b'\r'),
                            b't' => out.push(b'\t'),
                            b'u' => {
                                let h = std::str::from_utf8(
                                    self.s.get(self.i..self.i + 4).ok_or("short \\u")?,
                                )
                                .map_err(|e| e.to_string())?;
                                let n = u32::from_str_radix(h, 16).map_err(|e| e.to_string())?;
                                let ch = char::from_u32(n).ok_or("bad \\u")?;
                                let mut b = [0; 4];
                                out.extend_from_slice(ch.encode_utf8(&mut b).as_bytes());
                                self.i += 4;
                            }
                            _ => return Err(format!("bad escape \\{}", e as char)),
                        }
                    }
                    c if c < 0x20 => return Err("raw control character in string".into()),
                    c => out.push(c),
                }
            }
        }
        fn value(&mut self) -> Result<J, String> {
            self.ws();
            match self.s.get(self.i).copied() {
                Some(b'{') => {
                    self.i += 1;
                    let mut v = Vec::new();
                    self.ws();
                    if self.s.get(self.i) == Some(&b'}') {
                        self.i += 1;
                        return Ok(J::Obj(v));
                    }
                    loop {
                        let k = self.string()?;
                        self.eat(b':')?;
                        v.push((k, self.value()?));
                        self.ws();
                        match self.s.get(self.i) {
                            Some(b',') => self.i += 1,
                            Some(b'}') => {
                                self.i += 1;
                                return Ok(J::Obj(v));
                            }
                            _ => return Err(format!("bad object at {}", self.i)),
                        }
                    }
                }
                Some(b'[') => {
                    self.i += 1;
                    let mut v = Vec::new();
                    self.ws();
                    if self.s.get(self.i) == Some(&b']') {
                        self.i += 1;
                        return Ok(J::Arr(v));
                    }
                    loop {
                        v.push(self.value()?);
                        self.ws();
                        match self.s.get(self.i) {
                            Some(b',') => self.i += 1,
                            Some(b']') => {
                                self.i += 1;
                                return Ok(J::Arr(v));
                            }
                            _ => return Err(format!("bad array at {}", self.i)),
                        }
                    }
                }
                Some(b'"') => Ok(J::Str(self.string()?)),
                Some(b't') => self.lit("true", J::Bool(true)),
                Some(b'f') => self.lit("false", J::Bool(false)),
                Some(b'n') => self.lit("null", J::Null),
                Some(c) if c == b'-' || c.is_ascii_digit() => {
                    let start = self.i;
                    while self.s.get(self.i).is_some_and(|c| {
                        matches!(c, b'-' | b'+' | b'.' | b'e' | b'E') || c.is_ascii_digit()
                    }) {
                        self.i += 1;
                    }
                    let t =
                        std::str::from_utf8(&self.s[start..self.i]).map_err(|e| e.to_string())?;
                    // JSON forbids a leading '+', a leading zero before digits and a bare '.'.
                    if t.starts_with('+') || t.ends_with('.') || t.starts_with('.') {
                        return Err(format!("bad number {t}"));
                    }
                    t.parse().map(J::Num).map_err(|_| format!("bad number {t}"))
                }
                _ => Err(format!("unexpected input at {}", self.i)),
            }
        }
    }

    fn parse(text: &str) -> Result<J, String> {
        let mut p = P {
            s: text.as_bytes(),
            i: 0,
        };
        let v = p.value()?;
        p.ws();
        if p.i == p.s.len() {
            Ok(v)
        } else {
            Err(format!("trailing input at {}", p.i))
        }
    }

    fn field<'a>(o: &'a [(String, J)], k: &str) -> &'a J {
        &o.iter()
            .find(|(n, _)| n == k)
            .unwrap_or_else(|| panic!("missing {k}"))
            .1
    }

    #[test]
    fn json_strings_survive_escaping() {
        for s in [
            "plain",
            "a \"quoted\" word",
            "back\\slash",
            "line\nbreak\ttab\r",
            "control \u{1} \u{1f}",
            "unicode µ ° → 日本",
            "",
        ] {
            assert_eq!(parse(&json_string(s)), Ok(J::Str(s.to_string())), "{s:?}");
        }
    }

    #[test]
    fn the_checker_rejects_bad_json() {
        for bad in [
            "{",
            "[1,]",
            "{\"a\" 1}",
            "\"abc",
            "{\"a\":1}x",
            "[+1]",
            "\"\\x\"",
            "[01.]",
        ] {
            assert!(parse(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn json_metadata_parses_and_matches_the_table() {
        let J::Obj(root) = parse(&json()).expect("valid JSON") else {
            panic!("root is not an object")
        };
        assert_eq!(field(&root, "version"), &J::Num(1.0));
        let J::Arr(list) = field(&root, "parameters") else {
            panic!("parameters is not an array")
        };
        assert_eq!(list.len(), PARAMS.len());
        // The text is the f32's shortest form, so it must read back to the
        // same f32 (an i32 is exact in f64).
        let same = |j: &J, v: ParamValue| match (j, v) {
            (J::Num(x), ParamValue::F32(y)) => (*x as f32).to_bits() == y.to_bits(),
            (J::Num(x), ParamValue::I32(y)) => *x == f64::from(y),
            _ => false,
        };
        for (item, d) in list.iter().zip(PARAMS) {
            let J::Obj(o) = item else {
                panic!("item is not an object")
            };
            assert_eq!(field(o, "name"), &J::Str(d.name.to_string()));
            let want = if matches!(d.default, ParamValue::I32(_)) {
                "Int32"
            } else {
                "Float"
            };
            assert_eq!(field(o, "type"), &J::Str(want.to_string()));
            assert!(same(field(o, "default"), d.default), "{} default", d.name);
            assert!(same(field(o, "min"), d.min), "{} min", d.name);
            assert!(same(field(o, "max"), d.max), "{} max", d.name);
            assert_eq!(field(o, "units"), &J::Str(d.unit.to_string()));
            assert_eq!(field(o, "group"), &J::Str(d.group.title().to_string()));
            assert_eq!(field(o, "shortDesc"), &J::Str(d.description.to_string()));
            assert_eq!(field(o, "rebootRequired"), &J::Bool(false));
        }
    }

    #[test]
    fn list_has_a_line_per_parameter_and_the_reference_value() {
        let text = list().expect("list");
        assert_eq!(text.lines().count(), PARAMS.len() + 1);
        let line = text
            .lines()
            .find(|l| l.starts_with("RATE_ROLL_P "))
            .expect("line");
        assert!(line.contains("28"), "{line}");
    }

    #[test]
    fn doc_has_every_parameter_once_in_its_group() {
        let text = doc();
        for d in PARAMS {
            assert_eq!(
                text.matches(&format!("| `{}` |", d.name)).count(),
                1,
                "{}",
                d.name
            );
        }
        for g in ParamGroup::ALL {
            assert!(
                text.contains(&format!("## {}\n", g.title())),
                "{}",
                g.title()
            );
        }
    }
}
